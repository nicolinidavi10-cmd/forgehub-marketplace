alter table public.products
  add column if not exists product_code text;

update public.products
set product_code = 'PRD-' || lpad(id::text, 5, '0')
where product_code is null or btrim(product_code) = '';

create unique index if not exists products_product_code_uidx
  on public.products (lower(btrim(product_code)))
  where product_code is not null and btrim(product_code) <> '';

-- ----------------------------------------------------------
-- 2) FORMAS DE PAGAMENTO
-- ----------------------------------------------------------

create table if not exists public.payment_methods (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.payment_methods (code, name, active, sort_order)
values
  ('pix', 'Pix', true, 1),
  ('credit', 'Cartão de crédito', true, 2),
  ('boleto', 'Boleto bancário', true, 3)
on conflict (code) do update
set name = excluded.name,
    sort_order = excluded.sort_order;

alter table public.payment_methods enable row level security;

drop policy if exists "payment_methods_active_select" on public.payment_methods;
create policy "payment_methods_active_select"
on public.payment_methods
for select
to authenticated
using (active = true or public.is_admin());

drop policy if exists "payment_methods_admin_all" on public.payment_methods;
create policy "payment_methods_admin_all"
on public.payment_methods
for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

grant select on public.payment_methods to authenticated;

create or replace function public.admin_set_payment_method(
  p_code text,
  p_active boolean
)
returns boolean
language plpgsql
security definer
set search_path = public
as $function$
begin
  if not public.is_admin() then
    raise exception 'Apenas administradores podem alterar formas de pagamento.';
  end if;

  update public.payment_methods
  set active = coalesce(p_active, false),
      updated_at = now()
  where code = lower(trim(coalesce(p_code, '')));

  if not found then
    raise exception 'Forma de pagamento não encontrada.';
  end if;

  return true;
end;
$function$;

revoke all on function public.admin_set_payment_method(text, boolean) from public;
grant execute on function public.admin_set_payment_method(text, boolean) to authenticated;

