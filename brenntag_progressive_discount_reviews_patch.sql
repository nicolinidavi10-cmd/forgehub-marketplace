create table if not exists public.order_reviews (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  customer_id uuid not null references auth.users(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text not null default '' check (char_length(comment) <= 1000),
  created_at timestamptz not null default now()
);

create index if not exists order_reviews_customer_idx
  on public.order_reviews(customer_id);

create index if not exists order_reviews_order_idx
  on public.order_reviews(order_id);

alter table public.order_reviews enable row level security;

drop policy if exists "order_reviews_customer_select" on public.order_reviews;
create policy "order_reviews_customer_select"
on public.order_reviews
for select
to authenticated
using (customer_id = auth.uid() or public.is_admin());

drop policy if exists "order_reviews_admin_select" on public.order_reviews;
create policy "order_reviews_admin_select"
on public.order_reviews
for select
to authenticated
using (public.is_admin());

create or replace function public.submit_order_review(
  p_order_id bigint,
  p_rating integer,
  p_comment text default ''
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_customer uuid;
  v_status public.order_status;
begin
  if auth.uid() is null then raise exception 'Usuário não autenticado.'; end if;
  if p_rating is null or p_rating < 1 or p_rating > 5 then
    raise exception 'A nota deve estar entre 1 e 5.';
  end if;

  select customer_id, status
  into v_customer, v_status
  from public.orders
  where id = p_order_id;

  if not found then raise exception 'Pedido não encontrado.'; end if;
  if v_customer <> auth.uid() then raise exception 'Você só pode avaliar suas próprias compras.'; end if;
  if v_status <> 'Concluído' then
    raise exception 'A avaliação só pode ser enviada depois que o pedido for concluído.';
  end if;

  if exists (select 1 from public.order_reviews where order_id = p_order_id) then
    raise exception 'Este pedido já foi avaliado.';
  end if;

  insert into public.order_reviews(order_id, customer_id, rating, comment)
  values(p_order_id, auth.uid(), p_rating, left(coalesce(trim(p_comment),''),1000));

  return true;
end;
$$;

revoke all on function public.submit_order_review(bigint,integer,text) from public;
grant execute on function public.submit_order_review(bigint,integer,text) to authenticated;

